/**
 * Rank-quality metrics over a fused retrieval list and a document-level judgement.
 *
 * Coverage (Phase 2) can only say how much retrieved text we could join back. It cannot say whether
 * the docling re-ingest retrieved *better* or merely retrieved *more* — a 6x chunk count raises
 * coverage counts mechanically. These metrics can, because they are all sensitive to *where* the
 * right document landed, not just whether something landed.
 *
 * ## Relevance attaches at document level (plan decision C)
 *
 * A candidate is relevant iff its `documentId` appears in the judgement with `gain > 0`. Chunk ids
 * are regenerated by every re-ingest, so a chunk-level label set is dead the moment the corpus it
 * was written against is rebuilt — which is the exact event this phase exists to measure across.
 * Document ids survive. The cost is real and worth naming: retrieving the wrong 400 tokens of the
 * right SDS scores as a hit here. That blind spot is what `entity-recall.ts` covers, and the two
 * must be read together.
 *
 * ## Unscorable is never zero
 *
 * Every metric returns {@link ScoreResult}. An episode we could not measure returns
 * `unscorable(reason)` and is excluded from means, with the reason preserved so the aggregate can
 * report it. Collapsing any of these into 0 turns a labelling gap or a stale chunk join into an
 * apparent retrieval collapse — the single most likely way this harness could produce a confident
 * wrong answer about docling.
 *
 * Pure: no DB, no clock, no randomness.
 */

import { fuseEpisode, type FusedCandidate, type FusedRanking } from './fuse';
import {
  scored,
  unscorable,
  type DocumentRelevance,
  type Judgement,
  type RetrievalEpisode,
  type ScoreResult,
  type ScoringOptions,
  type Unscorable,
} from './types';

/** Everything the per-metric computations need, prepared once per episode. */
export type RankContext = {
  episode: RetrievalEpisode;
  judgement: Judgement;
  options: ScoringOptions;
  fused: FusedRanking;
  /** `documentId` → gain, for judged documents with `gain > 0`. */
  gains: Map<string, number>;
  /** Distinct judged-relevant documents. The denominator for recall and AP. */
  relevantCount: number;
};

const positiveGains = (documents: readonly DocumentRelevance[]): Map<string, number> => {
  const gains = new Map<string, number>();
  for (const document of documents) {
    if (document.gain <= 0) continue;
    // A document listed twice keeps its highest gain rather than its last, so label-file ordering
    // cannot change a score.
    const existing = gains.get(document.documentId);
    if (existing === undefined || document.gain > existing) gains.set(document.documentId, document.gain);
  }
  return gains;
};

/**
 * Decide whether an episode can be scored at all, and prepare it if so.
 *
 * The order of the gates is deliberate — the first true statement about the episode wins, from
 * most structural to most contingent:
 *
 * 1. `calls === null` → `no_retrieval_calls`. The payload predates `retrieval_calls`; we do not
 *    know what was retrieved. Backfilled runs are all null, so this gate fires for every episode
 *    recorded before Phase 0 shipped.
 * 2. no judgement, or an unlabelled one (`relevantDocuments` empty and not negative) →
 *    `no_judgement`. Unlabelled is not "nothing was relevant".
 * 3. negative example → `no_judgement` with detail `negative_example`. See {@link scoreEpisodeRank}.
 * 4. `coverage.resolvedShare` below `coverageFloor` → `coverage_below_floor`. Unresolved chunks are
 *    a stale join, not a retrieval failure. A null `resolvedShare` (every reference synthetic, so
 *    the denominator is 0) is *not* gated here: there is nothing to be stale.
 * 5. no candidates after fusion and `excludeKinds` → `empty_retrieval`.
 *
 * Gate 5 is the contestable one. An empty list on a positive item could be argued as a true zero —
 * retrieval was asked and produced nothing. We call it unscorable because the contract gives
 * `empty_retrieval` its own reason, and because the cause is usually upstream (the turn answered
 * from prior context, or every candidate was an excluded kind) rather than a ranking defect. The
 * consequence is that a retriever outage shows up as a spike in one unscorable bucket instead of a
 * plausible-looking drop in mean nDCG — which is the failure we would rather have.
 */
export const prepareRankContext = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
): ScoreResult<RankContext> => {
  if (episode.calls === null) {
    return unscorable('no_retrieval_calls', `episode ${episode.episodeId} predates retrieval_calls`);
  }
  if (judgement === null || judgement === undefined) {
    return unscorable('no_judgement', `no judgement for item ${episode.itemId}`);
  }
  if (judgement.isNegative) {
    return unscorable('no_judgement', 'negative_example');
  }
  if (judgement.relevantDocuments.length === 0) {
    return unscorable('no_judgement', `item ${episode.itemId} is unlabelled`);
  }

  const gains = positiveGains(judgement.relevantDocuments);
  if (gains.size === 0) {
    return unscorable('no_judgement', `item ${episode.itemId} has only zero-gain labels`);
  }

  const { resolvedShare } = episode.coverage;
  if (resolvedShare !== null && resolvedShare < options.coverageFloor) {
    return unscorable(
      'coverage_below_floor',
      `resolvedShare ${resolvedShare.toFixed(3)} < floor ${options.coverageFloor}`,
    );
  }

  const fused = fuseEpisode(episode, options);
  if (fused === null) {
    return unscorable('no_retrieval_calls', `episode ${episode.episodeId} predates retrieval_calls`);
  }
  if (fused.candidates.length === 0) {
    return unscorable('empty_retrieval', 'no candidates survived fusion and excludeKinds');
  }

  return scored({ episode, judgement, options, fused, gains, relevantCount: gains.size });
};

const isRelevant = (context: RankContext, candidate: FusedCandidate): boolean =>
  context.gains.has(candidate.documentId);

/** Candidates in the top `k` positions of the fused list. `k <= 0` yields an empty slice. */
const topK = (context: RankContext, k: number): FusedCandidate[] =>
  k <= 0 ? [] : context.fused.candidates.slice(0, k);

const withContext = <T>(
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
  compute: (context: RankContext) => T,
): ScoreResult<T> => {
  const prepared = prepareRankContext(episode, judgement, options);
  return prepared.scored ? scored(compute(prepared.value)) : prepared;
};

// ---------------------------------------------------------------------------
// Core computations. These take a prepared context and return plain numbers, so
// `scoreEpisodeRank` can compute the whole family from one fusion pass.
// ---------------------------------------------------------------------------

/** 1 when any judged-relevant document appears in the top `k`, else 0. */
export const computeHitAtK = (context: RankContext, k: number): number =>
  topK(context, k).some((candidate) => isRelevant(context, candidate)) ? 1 : 0;

/**
 * Distinct judged-relevant documents found in the top `k`, over all judged-relevant documents.
 *
 * Distinct is the operative word: five chunks of one relevant SDS are one document recalled. Under
 * a 6x chunk count that distinction is the whole ballgame — counting chunk hits would show docling
 * "improving recall" purely by fragmenting the same document across more positions.
 */
export const computeRecallAtK = (context: RankContext, k: number): number => {
  const found = new Set<string>();
  for (const candidate of topK(context, k)) {
    if (isRelevant(context, candidate)) found.add(candidate.documentId);
  }
  return found.size / context.relevantCount;
};

/**
 * Relevant positions in the top `k`, over the number of positions actually examined.
 *
 * The denominator is `min(k, listLength)`, not `k`. Textbook precision@k divides by k, which
 * penalises a retriever for returning fewer than k results — but list length here is set by the
 * tool's own top-k configuration, not by the ranking quality we are measuring, and the two arms of
 * a pre/post-docling comparison do not necessarily share it. Dividing by k would report a
 * configuration difference as a precision difference. Consequence to keep in mind when reading the
 * output: precision@10 over a 4-item list is precision over 4 items, so it is not comparable to
 * precision@10 over a 20-item list as a *count* of good hits — pair it with recall@k, which has a
 * fixed denominator.
 *
 * This one is positional, not per-document: two relevant chunks of the same document are two good
 * positions, because the model really did get two useful contexts.
 */
export const computePrecisionAtK = (context: RankContext, k: number): number => {
  const slice = topK(context, k);
  if (slice.length === 0) return 0;
  const relevant = slice.filter((candidate) => isRelevant(context, candidate)).length;
  return relevant / slice.length;
};

/** 1-based position of the first judged-relevant candidate; null when there is none. */
export const computeRankOfFirstRelevant = (context: RankContext): number | null => {
  const index = context.fused.candidates.findIndex((candidate) => isRelevant(context, candidate));
  return index === -1 ? null : index + 1;
};

/** `1 / rankOfFirstRelevant`, or 0 when nothing relevant was retrieved. Mean this for MRR. */
export const computeReciprocalRank = (context: RankContext): number => {
  const rank = computeRankOfFirstRelevant(context);
  return rank === null ? 0 : 1 / rank;
};

/**
 * Average precision over the full fused list.
 *
 * Because relevance is document-level, only the *first* candidate of each relevant document counts
 * as a new hit; later chunks of an already-credited document neither add a hit nor a new precision
 * term. Without that, a retriever could push AP up by returning the same document repeatedly, which
 * is precisely the behaviour a finer chunking makes easy.
 *
 * The denominator is the number of judged-relevant documents (not the number found), so failing to
 * retrieve a relevant document costs AP rather than being quietly dropped from the average.
 */
export const computeAveragePrecision = (context: RankContext): number => {
  const seen = new Set<string>();
  let hits = 0;
  let sum = 0;
  context.fused.candidates.forEach((candidate, index) => {
    if (!isRelevant(context, candidate)) return;
    if (seen.has(candidate.documentId)) return;
    seen.add(candidate.documentId);
    hits += 1;
    sum += hits / (index + 1);
  });
  return sum / context.relevantCount;
};

/**
 * Graded nDCG@k: `sum((2^gain - 1) / log2(position + 1))` over the top k, divided by the same sum
 * over the ideal ordering of the judgement's gains truncated at k.
 *
 * Two choices worth stating. First, gain is credited once per document — a repeat of an
 * already-credited document contributes 0 but still consumes a position, so fragmentation dilutes
 * nDCG instead of inflating it, and the metric stays bounded by an IDCG built from distinct
 * documents. Second, IDCG comes from the judgement, not from the retrieved list, so an episode that
 * retrieves none of three relevant documents scores 0 rather than being normalised against its own
 * poor result.
 */
export const computeNdcgAtK = (context: RankContext, k: number): number => {
  const credited = new Set<string>();
  let dcg = 0;
  topK(context, k).forEach((candidate, index) => {
    const gain = context.gains.get(candidate.documentId);
    if (gain === undefined || credited.has(candidate.documentId)) return;
    credited.add(candidate.documentId);
    dcg += (2 ** gain - 1) / Math.log2(index + 2);
  });

  const idealGains = [...context.gains.values()].sort((a, b) => b - a).slice(0, Math.max(k, 0));
  const idcg = idealGains.reduce((sum, gain, index) => sum + (2 ** gain - 1) / Math.log2(index + 2), 0);
  return idcg === 0 ? 0 : dcg / idcg;
};

// ---------------------------------------------------------------------------
// Episode-level public API. Each validates the episode itself, so a caller can
// reach for one metric without wiring the gate logic by hand.
// ---------------------------------------------------------------------------

export const hitAtK = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
  k: number,
): ScoreResult<number> => withContext(episode, judgement, options, (context) => computeHitAtK(context, k));

export const recallAtK = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
  k: number,
): ScoreResult<number> => withContext(episode, judgement, options, (context) => computeRecallAtK(context, k));

export const precisionAtK = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
  k: number,
): ScoreResult<number> =>
  withContext(episode, judgement, options, (context) => computePrecisionAtK(context, k));

/** Per-episode reciprocal rank. Mean the scored values across a set to get MRR. */
export const reciprocalRank = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
): ScoreResult<number> => withContext(episode, judgement, options, computeReciprocalRank);

export const averagePrecision = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
): ScoreResult<number> => withContext(episode, judgement, options, computeAveragePrecision);

export const ndcgAtK = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
  k: number,
): ScoreResult<number> => withContext(episode, judgement, options, (context) => computeNdcgAtK(context, k));

export const rankOfFirstRelevant = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
): ScoreResult<number | null> =>
  withContext(episode, judgement, options, computeRankOfFirstRelevant);

/** Metric key as it appears in {@link EpisodeRankScores.metrics}, e.g. `ndcg@10`. */
export const metricKey = (base: string, k?: number): string => (k === undefined ? base : `${base}@${k}`);

/** Metric bases that are not parameterised by k. */
export const SCALAR_METRICS = ['reciprocal_rank', 'average_precision'] as const;
/** Metric bases that are computed at every k in `options.ks`. */
export const AT_K_METRICS = ['hit', 'recall', 'precision', 'ndcg'] as const;

/** Every metric key a given `ks` produces, in report order. */
export const rankMetricKeys = (ks: readonly number[]): string[] => [
  ...SCALAR_METRICS,
  ...AT_K_METRICS.flatMap((base) => ks.map((k) => metricKey(base, k))),
];

export type EpisodeRankScores = {
  episodeId: string;
  itemId: string;
  runId: string;
  options: ScoringOptions;
  /** Null when the episode was unscorable before fusion could run. */
  fused: FusedRanking | null;
  /** Set on every metric when the whole episode was unscorable. */
  unscorable: Unscorable | null;
  /** Keyed by {@link metricKey}; every key in `rankMetricKeys(options.ks)` is present. */
  metrics: Record<string, ScoreResult<number>>;
  /** Kept out of `metrics` because its scored value is nullable and means "no relevant hit". */
  rankOfFirstRelevant: ScoreResult<number | null>;
};

/**
 * Score one episode on the whole rank-metric family in a single fusion pass.
 *
 * When the episode is unscorable, *every* metric carries the same {@link Unscorable} — the reason
 * is a property of the episode, not of the metric, and duplicating it keeps the aggregate's
 * per-metric reason breakdown honest without special cases.
 *
 * **Negative examples are unscorable here, deliberately.** For an item where the correct behaviour
 * is to retrieve nothing, recall has no denominator and precision has no relevant set; scoring one
 * as 0 would drag the mean down for behaving correctly, and scoring it as 1 would reward a
 * retriever that returns garbage. Negatives need their own measure — retrieval abstention rate, or
 * precision against an empty relevant set — so this function returns
 * `unscorable('no_judgement', 'negative_example')` and leaves the treatment to the caller, which
 * can select them by that detail string.
 */
export const scoreEpisodeRank = (
  episode: RetrievalEpisode,
  judgement: Judgement | null | undefined,
  options: ScoringOptions,
): EpisodeRankScores => {
  const prepared = prepareRankContext(episode, judgement, options);
  const keys = rankMetricKeys(options.ks);

  if (!prepared.scored) {
    const metrics: Record<string, ScoreResult<number>> = {};
    for (const key of keys) metrics[key] = prepared;
    return {
      episodeId: episode.episodeId,
      itemId: episode.itemId,
      runId: episode.runId,
      options,
      fused: episode.calls === null ? null : fuseEpisode(episode, options),
      unscorable: prepared,
      metrics,
      rankOfFirstRelevant: prepared,
    };
  }

  const context = prepared.value;
  const metrics: Record<string, ScoreResult<number>> = {
    reciprocal_rank: scored(computeReciprocalRank(context)),
    average_precision: scored(computeAveragePrecision(context)),
  };
  for (const k of options.ks) {
    metrics[metricKey('hit', k)] = scored(computeHitAtK(context, k));
    metrics[metricKey('recall', k)] = scored(computeRecallAtK(context, k));
    metrics[metricKey('precision', k)] = scored(computePrecisionAtK(context, k));
    metrics[metricKey('ndcg', k)] = scored(computeNdcgAtK(context, k));
  }

  return {
    episodeId: episode.episodeId,
    itemId: episode.itemId,
    runId: episode.runId,
    options,
    fused: context.fused,
    unscorable: null,
    metrics,
    rankOfFirstRelevant: scored(computeRankOfFirstRelevant(context)),
  };
};
