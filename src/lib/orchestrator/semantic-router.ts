/** Envelope format this build knows how to read. Bump alongside a breaking change to the file's shape. */
const SEMANTIC_ROUTER_EMBEDDINGS_FILE_FORMAT = 1;

type RouterState = {
  examplesVersion: string;
  embeddingModel: string;
  routes: RouteVectors[];
};

let state: RouterState | null = null;
/**
 * Memoized in-flight init. Next.js 16's App Router has no reliable single process-start hook that
 * fires in dev, in a serverless function, and in a long-lived node server alike (instrumentation
 * hooks run per-runtime and not at all for some entrypoints), so "pre-compute at startup" is
 * implemented as lazy-and-idempotent: the FIRST `classifyUserIntentSemantic` awaits this promise,
 * every later call and every concurrent caller shares it, and the resulting vectors live in module
 * scope for the life of the process — surviving across requests exactly as a startup hook would,
 * without depending on one existing.
 */
let initPromise: Promise<SemanticRouterInitResult> | null = null;
let lastInitResult: SemanticRouterInitResult | null = null;

function toRouteVectors(
  route: SmeAgentId,
  examples: readonly string[],
  vectors: readonly number[][],
): RouteVectors {
  return {
    route,
    examples,
    vectors,
    norms: vectors.map(vectorNorm),
  };
}

/**
 * Validate one route's entry from the pre-computed file against the LIVE `SEMANTIC_ROUTER_EXAMPLES`
 * corpus before trusting a single number in it — mirrors the diligence the old Redis cache payload
 * validation applied (`semantic-router-cache.ts`, deleted by B0-680), just against a file instead of
 * a network payload. A stale or corrupt entry is skipped (this route falls back to `ambiguous`
 * routing, same as an unreachable OpenAI call used to do), never trusted.
 */
function validateRouteEntry(
  examples: readonly string[],
  entry: { examples: string[]; vectors: number[][] } | undefined,
  dimensions: number,
): { vectors: number[][] } | { error: string } {
  if (!entry) return { error: 'missing from the embeddings file' };
  if (!Array.isArray(entry.examples) || entry.examples.length !== examples.length) {
    return { error: 'example count does not match semantic-router-examples.ts' };
  }
  for (let i = 0; i < examples.length; i += 1) {
    if (entry.examples[i] !== examples[i]) {
      return {
        error: `example text at index ${i} does not match semantic-router-examples.ts — regenerate via scripts/generate-semantic-router-embeddings.ts`,
      };
    }
  }
  if (!Array.isArray(entry.vectors) || entry.vectors.length !== examples.length) {
    return { error: 'vector count does not match its example count' };
  }
  for (const vector of entry.vectors) {
    if (
      !Array.isArray(vector) ||
      vector.length !== dimensions ||
      !vector.every((value) => Number.isFinite(value))
    ) {
      return { error: 'a stored vector has the wrong dimension or a non-finite value' };
    }
  }
  return { vectors: entry.vectors };
}

/**
 * Load and validate the pre-computed corpus embeddings from `semantic-router-embeddings.json`
 * (B0-680). Pure and synchronous — no OpenAI call, no Redis call, just local validation — but kept
 * `async` so its call site (`runInit`) does not have to change shape depending on which init
 * strategy is active.
 *
 * Every failure mode degrades to "skip this route" / "skip the whole file" rather than throwing:
 * a bad file must never crash the app at import time, only leave the router in the same degraded
 * fallback state an unreachable OpenAI call used to produce.
 */
function loadPrecomputedRoutes(
  embeddingModel: string,
  examplesVersion: string,
): { routes: RouteVectors[]; errors: string[] } {
  const errors: string[] = [];
  const routes: RouteVectors[] = [];
  const file = semanticRouterEmbeddingsFile;

  if (file.format !== SEMANTIC_ROUTER_EMBEDDINGS_FILE_FORMAT) {
    errors.push(
      `semantic-router-embeddings.json has format ${file.format}, expected ${SEMANTIC_ROUTER_EMBEDDINGS_FILE_FORMAT}`,
    );
    return { routes, errors };
  }
  if (file.examplesVersion !== examplesVersion) {
    errors.push(
      `semantic-router-embeddings.json was generated for examples version ${file.examplesVersion}, code is at ${examplesVersion} — regenerate via scripts/generate-semantic-router-embeddings.ts`,
    );
    return { routes, errors };
  }
  if (file.embeddingModel !== embeddingModel) {
    errors.push(
      `semantic-router-embeddings.json was generated with model ${file.embeddingModel}, current setting is ${embeddingModel}`,
    );
    return { routes, errors };
  }
  if (file.dimensions !== SEMANTIC_ROUTER_EMBEDDING_DIMENSIONS) {
    errors.push(
      `semantic-router-embeddings.json has ${file.dimensions} dimensions, expected ${SEMANTIC_ROUTER_EMBEDDING_DIMENSIONS}`,
    );
    return { routes, errors };
  }

  for (const route of SME_AGENT_IDS) {
    const examples = SEMANTIC_ROUTER_EXAMPLES[route] ?? [];
    if (examples.length === 0) {
      errors.push(`route ${route} has no examples`);
      continue;
    }

    const validated = validateRouteEntry(
      examples,
      file.routes[route],
      SEMANTIC_ROUTER_EMBEDDING_DIMENSIONS,
    );
    if ('error' in validated) {
      errors.push(`route ${route}: ${validated.error}`);
      continue;
    }
    routes.push(toRouteVectors(route, examples, validated.vectors));
  }

  return { routes, errors };
}

async function runInit(): Promise<SemanticRouterInitResult> {
  const embeddingModel = await getSemanticRouterEmbeddingModel();
  const examplesVersion = SEMANTIC_ROUTER_EXAMPLES_VERSION;
  const { routes, errors } = loadPrecomputedRoutes(embeddingModel, examplesVersion);

  const result: SemanticRouterInitResult = {
    examplesVersion,
    embeddingModel,
    routeCount: routes.length,
    exampleCount: routes.reduce((total, r) => total + r.vectors.length, 0),
    // 'static' whenever routes were loaded from the pre-computed file this call. ('memory' is
    // reported by `initSemanticRouter` for a warm process that skips this function entirely.)
    source: 'static',
    errors,
  };

  if (routes.length > 0) {
    state = { examplesVersion, embeddingModel, routes };
  }

  if (errors.length > 0) {
    logWarn('bex.semantic_router.init_degraded', {
      routeCount: result.routeCount,
      exampleCount: result.exampleCount,
      errors: errors.join('; '),
    });
  }

  lastInitResult = result;
  return result;
}

/**
 * Load (or re-use the in-memory copy of) every example embedding from the pre-computed file.
 * Idempotent and safe to call concurrently — concurrent callers share one in-flight promise, and a
 * warm process returns immediately with `source: 'memory'`. Never throws: a total failure resolves
 * with `routeCount: 0` and the reasons in `errors`, and clears the memo so the NEXT call can retry
 * (a permanently memoized failure would leave the router dead for the life of the process — this
 * matters less now that there is no network call to retry, but a corrected/regenerated file should
 * not require a process restart to pick up in a long-lived dev server).
 */
export async function initSemanticRouter(): Promise<SemanticRouterInitResult> {
  if (state && lastInitResult) {
    return { ...lastInitResult, source: 'memory' };
  }
  if (initPromise) return initPromise;

  initPromise = runInit().then((result) => {
    if (!state) initPromise = null;
    return result;
  });

  return initPromise;
}

// ---------------------------------------------------------------------------------------------
// Live message embedding cache (B0-648)
// ---------------------------------------------------------------------------------------------

/**
 * Same design as `intent-classifier.ts`'s result cache: promise-valued so concurrent callers share
 * one round-trip, TTL + max-entries so a long-lived process cannot grow unbounded, failures evicted
 * so a transient API error is not served for the rest of the TTL.
 *
 * This is what makes the "warm path" genuinely fast — on a hit the whole call is the cosine pass.
 */
export const SEMANTIC_ROUTER_CACHE_TTL_MS = 5 * 60_000;
const MAX_CACHE_ENTRIES = 256;

type EmbeddingCacheEntry = {
  expiresAt: number;
  promise: Promise<{ vector: number[]; norm: number }>;
};

const embeddingCache = new Map<string, EmbeddingCacheEntry>();
const cacheStats = { hits: 0, misses: 0 };

/**
 * `hash(model + examplesVersion + message + prior-turn-ids)`.
 *
 * Prior-turn ids are part of the key even though today only the message text is embedded (see
 * `classifyUserIntentSemantic`) — this keeps the key semantics identical to
 * `computeIntentClassifierCacheKey`, so a shadow-mode comparison of the two routers sees the same
 * hit/miss boundaries, and so folding conversational context into the embedded text later cannot
 * introduce a stale-cache bug.
 */
export function computeSemanticRouterCacheKey(
  message: string,
  priorMessages: PriorTurnMessage[] = [],
  embeddingModel: string,
): string {
  const ids = priorMessages.map((m) => m.id);
  const canonical = [
    `model:${embeddingModel}`,
    `examples:${SEMANTIC_ROUTER_EXAMPLES_VERSION}`,
    `msg:${message.length}:${message}`,
    `ids:${ids.length}:${ids.join(',')}`,
  ].join('|');
  return createHash('sha256').update(canonical, 'utf8').digest('hex');
}

function pruneCache(now: number): void {
  for (const [key, entry] of embeddingCache) {
    if (entry.expiresAt <= now) embeddingCache.delete(key);
  }
  while (embeddingCache.size >= MAX_CACHE_ENTRIES) {
    const oldest = embeddingCache.keys().next();
    if (oldest.done) break;
    embeddingCache.delete(oldest.value);
  }
}

/** Observability/test helper: message-embedding cache counters. */
export function getSemanticRouterCacheStats(): {
  hits: number;
  misses: number;
  size: number;
} {
  return {
    hits: cacheStats.hits,
    misses: cacheStats.misses,
    size: embeddingCache.size,
  };
}

/**
 * Test helper: forget the example corpus, the init memo, and every cached message embedding, so a
 * test can re-init against a different mock without leaking state across cases.
 */
export function resetSemanticRouterForTest(): void {
  state = null;
  initPromise = null;
  lastInitResult = null;
  embeddingCache.clear();
  cacheStats.hits = 0;
  cacheStats.misses = 0;
}

// ---------------------------------------------------------------------------------------------
// The decision (B0-648 / B0-650)
// ---------------------------------------------------------------------------------------------

type DecisionInput = {
  scores: SemanticRouteScore[];
  thresholds: { confidence: number; margin: number };
  latencyMs: number;
  embeddingMs: number;
  scoringMs: number;
  embeddingModel: string;
  examplesVersion: string;
  error: string | null;
};

/**
 * B0-650 — routing succeeds ONLY if BOTH gates pass: the top score clears the confidence threshold
 * ("is this a real match at all?") AND beats the runner-up by the margin threshold ("is it a clear
 * winner?"). Either failure, or any `error`, returns `path: 'fallback'` with `route: 'ambiguous'` —
 * and the decision still carries every score, both thresholds, and which gate failed, so a fallback
 * is diagnosable from the persisted trace rather than being an unexplained shrug.
 *
 * With a single route present the runner-up is treated as 0, so `margin === confidence`. That is the
 * conservative reading: with nothing to compare against there is no evidence of a *clear* winner
 * beyond the absolute score itself.
 */
export function buildSemanticRouteDecision({
  scores,
  thresholds,
  latencyMs,
  embeddingMs,
  scoringMs,
  embeddingModel,
  examplesVersion,
  error,
}: DecisionInput): SemanticRouteDecision {
  const top = scores[0];
  const confidence = top ? clamp01(top.similarity) : 0;
  const runnerUp = scores[1]?.similarity ?? 0;
  const margin = Math.max(0, confidence - runnerUp);

  const confidencePassed = Boolean(top) && confidence >= thresholds.confidence;
  const marginPassed = Boolean(top) && margin >= thresholds.margin;
  const routed =
    error === null && top !== undefined && confidencePassed && marginPassed;

  return {
    route: routed ? top!.route : 'ambiguous',
    confidence,
    similarity: confidence,
    margin,
    path: routed ? 'semantic' : 'fallback',
    scores,
    thresholds,
    thresholdsPassed: { confidence: confidencePassed, margin: marginPassed },
    latencyMs: roundMs(latencyMs),
    embeddingMs: roundMs(embeddingMs),
    scoringMs: roundMs(scoringMs),
    embeddingModel,
    examplesVersion,
    error,
  };
}

async function resolveThresholds(): Promise<{
  confidence: number;
  margin: number;
}> {
  const [confidence, margin] = await Promise.all([
    getSemanticRouterConfidenceThreshold(),
    getSemanticRouterMarginThreshold(),
  ]);
  return { confidence, margin };
}

/**
 * B0-648 — classify a message by semantic similarity to the example corpus.
 *
 * `priorMessages` is accepted for signature parity with `classifyUserIntent` and participates in the
 * embedding cache key, but the embedded text is the CURRENT message alone: the example corpus is
 * made of single-utterance vectors, so concatenating history would pull the message vector away from
 * the space the corpus lives in and depress every score. Handling a context-dependent follow-up
 * ("and the shower stalls?") stays the LLM classifier's job.
 *
 * Latency, honestly: the ~10ms budget in the ticket applies to `scoringMs` (the cosine pass) and to
 * the whole warm call when the message embedding is cached (`embeddingMs === 0`). A COLD call is
 * dominated by the OpenAI embedding round-trip, which is tens to hundreds of ms and cannot be
 * inside 10ms; `embeddingMs` reports it truthfully rather than hiding it in a blended number.
 */
export async function classifyUserIntentSemantic(
  message: string,
  priorMessages: PriorTurnMessage[] = [],
): Promise<SemanticRouteDecision> {
  const startedAt = nowMs();
  const thresholds = await resolveThresholds();

  const degraded = (
    error: string,
    embeddingModel: string,
    embeddingMs = 0,
  ): SemanticRouteDecision =>
    buildSemanticRouteDecision({
      scores: [],
      thresholds,
      latencyMs: nowMs() - startedAt,
      embeddingMs,
      scoringMs: 0,
      embeddingModel,
      examplesVersion: SEMANTIC_ROUTER_EXAMPLES_VERSION,
      error,
    });

  const trimmed = message.trim();
  if (trimmed.length === 0) {
    return degraded('empty_message', await getSemanticRouterEmbeddingModel());
  }

  const init = await initSemanticRouter();
  const active = state;
  if (!active || active.routes.length === 0) {
    return degraded(
      init.errors[0] ?? 'semantic_router_not_initialized',
      init.embeddingModel,
    );
  }

  const cacheKey = computeSemanticRouterCacheKey(
    trimmed,
    priorMessages,
    active.embeddingModel,
  );
  const now = Date.now();
  const existing = embeddingCache.get(cacheKey);

  let embedded: { vector: number[]; norm: number };
  let embeddingMs = 0;

  if (existing && existing.expiresAt > now) {
    cacheStats.hits += 1;
    try {
      embedded = await existing.promise;
    } catch (error: unknown) {
      // Can only happen if a concurrent miss is still in flight and fails; treat as degraded.
      const reason = error instanceof Error ? error.message : String(error);
      return degraded(reason, active.embeddingModel);
    }
  } else {
    pruneCache(now);
    cacheStats.misses += 1;

    const promise = withSemanticRouterTimeout(
      EMBEDDING_TIMEOUT_MS,
      'classifyUserIntentSemantic',
      (signal) => embedBatch([trimmed], active.embeddingModel, signal),
    ).then(([vector]) => {
      const resolved = vector!;
      return { vector: resolved, norm: vectorNorm(resolved) };
    });

    embeddingCache.set(cacheKey, {
      expiresAt: now + SEMANTIC_ROUTER_CACHE_TTL_MS,
      promise,
    });

    const embeddingStartedAt = nowMs();
    try {
      embedded = await promise;
    } catch (error: unknown) {
      // Never cache a failure: a cached transient timeout would keep routing degraded for the TTL.
      embeddingCache.delete(cacheKey);
      const reason = error instanceof Error ? error.message : String(error);
      logError('bex.semantic_router.fallback', { reason });
      return degraded(
        reason,
        active.embeddingModel,
        nowMs() - embeddingStartedAt,
      );
    }
    embeddingMs = nowMs() - embeddingStartedAt;
  }

  if (embedded.norm <= 0) {
    return degraded(
      'zero_norm_message_embedding',
      active.embeddingModel,
      embeddingMs,
    );
  }

  const scoringStartedAt = nowMs();
  const scores = scoreRoutes(embedded.vector, embedded.norm, active.routes);
  const scoringMs = nowMs() - scoringStartedAt;

  return buildSemanticRouteDecision({
    scores,
    thresholds,
    latencyMs: nowMs() - startedAt,
    embeddingMs,
    scoringMs,
    embeddingModel: active.embeddingModel,
    examplesVersion: active.examplesVersion,
    error: null,
  });
}
