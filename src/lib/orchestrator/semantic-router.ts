/**
 * B0-647 / B0-648 / B0-650 / B0-680 — the semantic intent router.
 *
 * A cheap, deterministic alternative to the LLM classifier in `intent-classifier.ts`: embed the
 * user's message once, cosine it against a hand-authored example corpus (one set per SME route),
 * and route to the best-matching route only when it is BOTH a real match (confidence threshold) and
 * a clear winner (margin threshold). Anything else is `path: 'fallback'` / `route: 'ambiguous'`,
 * which the caller is expected to treat exactly as it treats the LLM classifier's `ambiguous`.
 *
 * B0-680 — the example corpus's embeddings are PRE-COMPUTED and checked into git as
 * `semantic-router-embeddings.json` (generated by `scripts/generate-semantic-router-embeddings.ts`)
 * rather than computed via OpenAI on first boot and shared via Redis (the former B0-654 design,
 * `semantic-router-cache.ts`, now deleted). Init is a pure local load-and-validate: no OpenAI call,
 * no Redis dependency, for the example corpus. A LIVE user message is still embedded via OpenAI on
 * every call — that half of the router is unavoidable and unchanged.
 *
 * Contract, mirroring `classifyUserIntent`: this module NEVER throws. An OpenAI outage, a stale or
 * missing embeddings file, a blank message — all degrade to a fallback decision carrying a non-null
 * `error`, because a router failure must not break the turn.
 *
 * Deliberately NOT wired into the workflow here. The rollout levers
 * (`BEX_SEMANTIC_ROUTER_ENABLED` / `BEX_SEMANTIC_ROUTER_SHADOW_MODE`) and the decision to route on
 * this at all belong to the B0-649 integration.
 */

export type SemanticRouterPath = 'semantic' | 'fallback';

/** Same value space as the LLM classifier's `IntentValue`. Always 'ambiguous' when path === 'fallback'. */
export type SemanticRouteLabel = IntentValue;

export type SemanticRouteScore = { route: SmeAgentId; similarity: number };

export type SemanticRouteDecision = {
  route: SemanticRouteLabel;
  /** max similarity across routes, 0..1 */
  confidence: number;
  /** alias of confidence — both names are load-bearing for callers, so both are populated */
  similarity: number;
  /** top similarity minus runner-up similarity */
  margin: number;
  path: SemanticRouterPath;
  /** every route's score, sorted desc by similarity */
  scores: SemanticRouteScore[];
  thresholds: { confidence: number; margin: number };
  thresholdsPassed: { confidence: boolean; margin: boolean };
  /** total wall-clock ms for this call */
  latencyMs: number;
  /** ms spent on the embedding round-trip specifically (0 on a cache hit) */
  embeddingMs: number;
  /** ms spent on cosine scoring specifically — this is what the ~10ms budget really governs */
  scoringMs: number;
  embeddingModel: string;
  examplesVersion: string;
  /** non-null means degraded (API error / not initialized); path is then 'fallback' */
  error: string | null;
};

export type SemanticRouterInitResult = {
  examplesVersion: string;
  embeddingModel: string;
  routeCount: number;
  exampleCount: number;
  /** 'static' = loaded (this call) from the pre-computed `semantic-router-embeddings.json`; 'memory' = a warm process reused the corpus already loaded by an earlier call. */
  source: 'static' | 'memory';
  errors: string[];
};

// ---------------------------------------------------------------------------------------------
// Timing helpers
// ---------------------------------------------------------------------------------------------

/**
 * `performance.now()` rather than `Date.now()`: the cosine pass is well under a millisecond, and a
 * whole-millisecond clock would report it as "0ms" and make the latency budget unmeasurable.
 */
const nowMs = (): number => performance.now();

/** Sub-millisecond precision kept (3dp) so `scoringMs` is a real number, not a rounded-to-zero one. */
const roundMs = (ms: number): number => Math.round(ms * 1000) / 1000;

/**
 * Bounded ceiling so a hung OpenAI call degrades instead of hanging the turn. Mirrors
 * `withRouterTimeout`. Only guards the LIVE per-message embedding call now — the example corpus is
 * pre-computed (B0-680) and never calls OpenAI at init.
 */
const EMBEDDING_TIMEOUT_MS = 5_000;

async function withSemanticRouterTimeout<T>(
  budgetMs: number,
  label: string,
  run: (signal: AbortSignal) => Promise<T>,
): Promise<T> {
  const controller = new AbortController();
  const budget = Math.max(0, Math.floor(budgetMs));
  let timer: ReturnType<typeof setTimeout> | undefined;

  try {
    return await Promise.race([
      run(controller.signal),
      new Promise<never>((_resolve, reject) => {
        timer = setTimeout(() => {
          controller.abort();
          reject(new Error(`${label} exceeded its ${budget}ms timeout`));
        }, budget);
      }),
    ]);
  } finally {
    if (timer) clearTimeout(timer);
  }
}

