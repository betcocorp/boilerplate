// Embedding (B0-647) — LIVE messages only since B0-680; the example corpus is pre-computed.
// ---------------------------------------------------------------------------------------------

/**
 * Why not `createEmbedding()` from `~/lib/rag/embeddings.ts`: that helper is tuned for the RAG
 * corpus's batch-sync jobs, and this call sits directly on a user's turn — the router talks to
 * `getOpenAIClient()` directly so it owns its own timeout/retry policy, and enforces the SAME
 * 3072-dimension invariant `createEmbedding` does (see `SEMANTIC_ROUTER_EMBEDDING_DIMENSIONS`).
 * That invariant is also why `SEMANTIC_ROUTER_EMBEDDING_MODEL` only accepts 3072-dim models.
 *
 * Still accepts a batch of inputs (not just one string) even though every live call today embeds a
 * single message — the pre-computed example corpus used to be built through this same function
 * before B0-680, and keeping the signature batched costs nothing and avoids a needless second code
 * path if a future caller ever needs to embed more than one string at once.
 */
async function embedBatch(
  inputs: readonly string[],
  model: string,
  signal: AbortSignal,
): Promise<number[][]> {
  const client = getOpenAIClient();
  const response = await client.embeddings.create(
    { model, input: [...inputs] },
    // maxRetries 0 for the same reason the LLM router uses it: the SDK's backoff+replay can never
    // finish inside our budget, so a transient failure would just become a guaranteed timeout.
    { signal, maxRetries: 0 },
  );

  if (response.data.length !== inputs.length) {
    throw new Error(
      `Expected ${inputs.length} embeddings from OpenAI but received ${response.data.length}.`,
    );
  }

  return response.data.map((item, index) => {
    const vector = item.embedding;
    if (
      !Array.isArray(vector) ||
      vector.length !== SEMANTIC_ROUTER_EMBEDDING_DIMENSIONS
    ) {
      throw new Error(
        `Embedding ${index} had ${vector?.length ?? 0} dimensions; expected ${SEMANTIC_ROUTER_EMBEDDING_DIMENSIONS}.`,
      );
    }
    return vector;
  });
}

// ---------------------------------------------------------------------------------------------
// Similarity math (B0-648)
// ---------------------------------------------------------------------------------------------

/** L2 norm. Returned as 0 for a zero/degenerate vector so callers can reject it explicitly. */
export function vectorNorm(vector: readonly number[]): number {
  let sum = 0;
  for (const value of vector) sum += value * value;
  const norm = Math.sqrt(sum);
  return Number.isFinite(norm) ? norm : 0;
}

/**
 * Cosine similarity with PRE-COMPUTED norms — the hot path. OpenAI returns L2-normalized vectors,
 * so cosine reduces to a plain dot product, but we still divide by the stored norms rather than
 * assuming: a JSON round-trip through `semantic-router-embeddings.json`, or a future non-OpenAI
 * provider, can leave a norm that is not exactly 1. A zero/NaN norm or a length mismatch yields 0
 * ("no match") instead of NaN, which would otherwise silently win or lose comparisons.
 */
export function cosineSimilarityWithNorms(
  a: readonly number[],
  normA: number,
  b: readonly number[],
  normB: number,
): number {
  if (a.length !== b.length || a.length === 0) return 0;
  if (
    !Number.isFinite(normA) ||
    !Number.isFinite(normB) ||
    normA <= 0 ||
    normB <= 0
  )
    return 0;

  let dot = 0;
  for (let i = 0; i < a.length; i += 1) dot += a[i]! * b[i]!;

  const similarity = dot / (normA * normB);
  return Number.isFinite(similarity) ? similarity : 0;
}

/** Convenience wrapper that derives both norms. Used by tests and any non-hot-path caller. */
export function cosineSimilarity(
  a: readonly number[],
  b: readonly number[],
): number {
  return cosineSimilarityWithNorms(a, vectorNorm(a), b, vectorNorm(b));
}

/** One route's embedded example corpus, with norms cached so scoring is pure multiply-add. */
export type RouteVectors = {
  route: SmeAgentId;
  examples: readonly string[];
  vectors: readonly number[][];
  norms: readonly number[];
};

const clamp01 = (n: number): number => Math.max(0, Math.min(1, n));

/**
 * Score every route as the MAXIMUM cosine similarity over that route's examples, then sort desc.
 *
 * Max, not mean, on purpose: the corpus is a set of DISTINCT phrasings, so a message about
 * burnishing matches the burnishing example strongly and the wood-floor-refinish example weakly.
 * Averaging would let a route's own breadth dilute its best evidence — and would make adding a
 * good-but-unrelated example to a route measurably WORSE for that route, which is a perverse
 * incentive for anyone maintaining `semantic-router-examples.ts`. One strongly-matching example is
 * the signal we want; the margin threshold is what protects us from a lucky single match.
 *
 * Similarities are clamped into [0,1]: a negative cosine is "less than no match", and `confidence`
 * is documented as 0..1. In practice OpenAI text embeddings of English sentences essentially never
 * go negative, so this clamp changes nothing about real ordering.
 */
export function scoreRoutes(
  messageVector: readonly number[],
  messageNorm: number,
  routes: readonly RouteVectors[],
): SemanticRouteScore[] {
  const scores: SemanticRouteScore[] = [];

  for (const route of routes) {
    let best = 0;
    for (let i = 0; i < route.vectors.length; i += 1) {
      const similarity = cosineSimilarityWithNorms(
        messageVector,
        messageNorm,
        route.vectors[i]!,
        route.norms[i]!,
      );
      if (similarity > best) best = similarity;
    }
    scores.push({ route: route.route, similarity: clamp01(best) });
  }

  return scores.sort((a, b) => b.similarity - a.similarity);
}

